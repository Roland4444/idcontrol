'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const get = name => fs.readFileSync(path.join(root,name),'utf8');
const engine = get('src/engine.rs');
const web = get('src/web.rs');
const contractor = get('src/contractor.rs');
const block1 = get('src/block1.rs');
const migration = get('migrations/017_block1_completeness.sql');
const assertIncludes = (text,fragment,label) => assert.ok(text.includes(fragment),label);
assertIncludes(engine,'block1::current_delivery', 'manual checks must select current delivery');
assertIncludes(engine,'analyze_internal(db,catalog,package_id,source,Some(&scope))', 'contractor checks must be delivery-scoped');
assertIncludes(engine,'block1::counted_unique_codes', 'count unique current documents per catalogue code');
assertIncludes(engine,'block1::evidence_count', 'linked evidence must be scoped');
assertIncludes(engine,'IMPORT-GAP', 'missing scanner imports are not falsely presented as absent files');
assertIncludes(engine,'block1_approved_at IS NOT NULL', 'checklist approval cannot be inferred');
assertIncludes(contractor,'"contractor_review",submission_id,&relative_prefix', 'review ties to submitted revision');
assertIncludes(web,'SELECT block1_approved_by', 'checklist status is displayed');
assertIncludes(web,'current_delivery(&st.db,id)', 'UI respects chosen delivery');
assertIncludes(web,'block1::is_delivery_id(&doc,scope.as_ref())', 'cannot link old-revision evidence');
assertIncludes(web,'/checklist/approve', 'explicit approval action');
assertIncludes(web,'minimum_', 'per-code quantitative requirements');
assertIncludes(web,'/support/from-template', 'engineer can add TЗ templates selectively');
assertIncludes(migration,'package_block1_approvals', 'approval history');
assertIncludes(migration,'package_support_evidence', 'supporting document linkage');
assertIncludes(migration,'ADD COLUMN IF NOT EXISTS submission_id', 'historical run links');
const suppliers=[...block1.matchAll(/SupportTemplate\{code:"S\d\d"/g)];
const labs=[...block1.matchAll(/SupportTemplate\{code:"L\d\d"/g)];
assert.equal(suppliers.length,19,'19 supplier groups must be suggested');
assert.equal(labs.length,12,'12 laboratory groups must be suggested');
assert.ok(!migration.includes('DROP TABLE'),'upgrade must be additive');
assert.ok(!migration.includes('TRUNCATE'),'do not erase database');
console.log('OK: Block 1 source wiring, strict delivery scope, quantities, 19+12 templates, references, approval and additive migration');
